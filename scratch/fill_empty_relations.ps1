$updatedCount = 0
foreach ($charHeader in $relationsMap.Keys) {
    $charIdx = $xml.IndexOf($charHeader)
    if ($charIdx -lt 0) {
        Write-Error "Could not find character header: $charHeader"
        continue
    }
    $tblStart = $xml.IndexOf("<w:tbl>", $charIdx)
    $tblEnd = $xml.IndexOf("</w:tbl>", $tblStart) + 8
    $tblXml = $xml.Substring($tblStart, $tblEnd - $tblStart)

    # Keep the table properties, grid, and first header row (<w:tr>...</w:tr>)
    $firstTrEnd = $tblXml.IndexOf("</w:tr>") + 7
    $tblPrefix = $tblXml.Substring(0, $firstTrEnd)

    $rowsList = $relationsMap[$charHeader]
    $newRowsXml = ""
    foreach ($pair in $rowsList) {
        $newRowsXml += Build-FilledRow $pair[0] $pair[1]
    }
    # Pad with blank rows so there are at least 5 data rows in total
    $blankNeeded = 5 - $rowsList.Count
    if ($blankNeeded -gt 0) {
        for ($b = 0; $b -lt $blankNeeded; $b++) {
            $newRowsXml += Build-BlankRow
        }
    }

    $newTblXml = $tblPrefix + $newRowsXml + "</w:tbl>"
    $xml = $xml.Substring(0, $tblStart) + $newTblXml + $xml.Substring($tblEnd)
    $updatedCount++
}

